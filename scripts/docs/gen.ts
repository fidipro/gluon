/** The `Environment:` block of an installer's header comment: name → text (continuation lines joined). */
export function installerEnv(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  const lines = text.replace(/\r/g, "").split("\n");
  const start = lines.findIndex((l) => /^[#\s]*Environment:\s*$/.test(l));
  if (start === -1) return out;
  let current: string | undefined;
  for (const raw of lines.slice(start + 1)) {
    const line = raw.replace(/^#/, "");
    const m = line.match(/^\s+(GLUON_[A-Z_]+)\s{2,}(.*)$/);
    if (m) {
      current = m[1]!;
      out[current] = m[2]!.trim();
    } else if (current && /^\s{10,}\S/.test(line)) out[current] += ` ${line.trim()}`;
    else break;
  }
  return out;
}

