const read = (path: string): string => readFileSync(join(ROOT, path), "utf8");
/** A table cell: no pipes, no line breaks. */
const cell = (s: string | undefined): string => (s ?? "").replace(/\s*\n\s*/g, " ").replaceAll("|", "\\|");
const table = (head: string[], rows: string[][]): string => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");
const code = (s: string): string => `\`${s}\``;
const fence = (lang: string, text: string): string => `\`\`\`${lang}\n${text.replace(/\n$/, "")}\n\`\`\``;
const need = <T>(map: Record<string, T>, key: string, what: string): T => {
  if (!(key in map)) throw new Error(`scripts/docs/gen.ts: ${what} "${key}" has no description: add it next to the others`);
  return map[key]!;
};

/** Starlight frontmatter, the "generated" note (an HTML comment: readers of the site don't need it), the body and the freshness comment every Markdown file ends with. */
function page(title: string, description: string, sources: string[], body: string): string {
  return `---
title: ${JSON.stringify(title)}
description: ${JSON.stringify(description)}
---

<!-- Generated by \`bun run docs:gen\` from ${sources.join(", ")}. Do not edit by hand. -->

${body.trim()}

<!-- Keeping this file fresh: generated; run bun run docs:gen after changing ${sources.join(", ")}. -->
`;
}

